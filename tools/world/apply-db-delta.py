#!/usr/bin/env python3
"""Turn an Offline DAoC release's db-<version>.json (the world-DB delta shipped in its game patch)
into a world patch, and check it against our current world first.

  apply-db-delta.py <db-delta.json> <current world.sqlite> <out .sql>

<current world.sqlite> is our world WITHOUT the new patch: the DB the 200-* (and earlier 2NN-*)
patches produce, built with `DaocWorldBuilder --patches <folder of those patches>`.

Checks (the run fails, and writes nothing, if any is off):
  * every Update's "Old" row equals the row in our world (LastTimeRowUpdated ignored),
  * every Insert's key is absent (or already identical), every Delete's row exists,
  * after applying the SQL to a COPY of the world, every "New" row is present and the counts match
    the delta's Summary.
Output is deterministic, so regenerating gives the same file. Name it 2NN-offline-<version>.sql with
the next free NN (210 for 0.37, 220 for 0.38); WorldBuilder runs patches in name order.
"""
import json, pathlib, shutil, sqlite3, sys, tempfile

delta_path, world_path, out_path = sys.argv[1], sys.argv[2], pathlib.Path(sys.argv[3])
delta = json.loads(pathlib.Path(delta_path).read_text(encoding="utf-8"))
version = delta["Version"]
ignore = {c.lower() for c in delta.get("IgnoreColumns", [])}

def lit(v):
    if v is None: return "NULL"
    if isinstance(v, bool): return "1" if v else "0"
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

def ident(n): return '"' + n.replace('"', '""') + '"'

con = sqlite3.connect(f"file:{world_path}?mode=ro", uri=True)
problems, lines = [], [f"-- Offline DAoC {version} world delta. Generated by tools/world/apply-db-delta.py from db-{version}.json; do not edit by hand."]

def rows_by_key(table, cols, key):
    sel = ", ".join(ident(c) for c in cols)
    kidx = [cols.index(k) for k in key]
    return {tuple(r[i] for i in kidx): list(r) for r in con.execute(f"SELECT {sel} FROM {ident(table)}")}

def same(cols, a, b):
    return all(x == y for c, x, y in zip(cols, a, b) if c.lower() not in ignore)

existing_tables = {r[0].lower() for r in con.execute("SELECT name FROM sqlite_master WHERE type='table'")}
for nt in delta.get("NewTables", []):
    if nt["Table"].lower() in existing_tables:
        continue  # the server's own schema already creates it
    lines.append(nt["Create"].replace("CREATE TABLE", "CREATE TABLE IF NOT EXISTS", 1) + ";")
    lines += [i.replace("CREATE INDEX", "CREATE INDEX IF NOT EXISTS", 1).replace("CREATE UNIQUE INDEX", "CREATE UNIQUE INDEX IF NOT EXISTS", 1) + ";" for i in nt.get("Indexes", [])]
for nc in delta.get("NewColumns", []):
    problems.append(f"NewColumns is not supported by this tool yet: {nc}")

expected = {}
for t in delta["Tables"]:
    name, cols, key = t["Table"], t["Columns"], t["Key"]
    cur = rows_by_key(name, cols, key)
    kidx = [cols.index(k) for k in key]
    k_of = lambda row: tuple(row[i] for i in kidx)
    want = {}
    insert_sql = lambda row: f"INSERT OR REPLACE INTO {ident(name)} ({', '.join(ident(c) for c in cols)}) VALUES ({', '.join(lit(v) for v in row)});"
    for row in t.get("Insert", []):
        if k_of(row) in cur and not same(cols, cur[k_of(row)], row):
            problems.append(f"{name}: Insert key {k_of(row)} already exists with different values")
        lines.append(insert_sql(row)); want[k_of(row)] = row
    for u in t.get("Update", []):
        old, new = u["Old"], u["New"]
        if k_of(old) not in cur: problems.append(f"{name}: Update key {k_of(old)} is not in our world")
        elif not same(cols, cur[k_of(old)], old): problems.append(f"{name}: Update key {k_of(old)}: our row differs from the delta's Old row")
        lines.append(insert_sql(new)); want[k_of(new)] = new
    for d in t.get("Delete", []):
        row = d if len(d) == len(cols) else None
        k = k_of(row) if row else tuple(d)
        if k not in cur: problems.append(f"{name}: Delete key {k} is not in our world")
        lines.append(f"DELETE FROM {ident(name)} WHERE " + " AND ".join(f"{ident(c)} = {lit(v)}" for c, v in zip(key, k)) + ";")
        want[k] = None
    expected[name] = (cols, key, want)

if problems:
    print(f"{len(problems)} problem(s); nothing written:"); [print("  " + p) for p in problems[:25]]; sys.exit(1)

sql = "\n".join(lines) + "\n"
tmp = pathlib.Path(tempfile.mkdtemp()) / "check.sqlite"
shutil.copyfile(world_path, tmp)
chk = sqlite3.connect(tmp); chk.executescript(sql)
bad = 0
for name, (cols, key, want) in expected.items():
    cur = {}
    kidx = [cols.index(k) for k in key]
    for r in chk.execute(f"SELECT {', '.join(ident(c) for c in cols)} FROM {ident(name)}"): cur[tuple(r[i] for i in kidx)] = list(r)
    for k, row in want.items():
        if (row is None) != (k not in cur) or (row is not None and not same(cols, cur[k], row)): bad += 1
    s = delta["Summary"].get(name, {})
    print(f"  {name:14} +{s.get('added', 0)} ~{s.get('changed', 0)} -{s.get('removed', 0)}")
if bad: print(f"{bad} rows differ after applying; nothing written"); sys.exit(1)
out_path.write_text(sql, encoding="utf-8")
print(f"wrote {out_path} ({len(lines)} statements); all rows verified against Old/New values")
